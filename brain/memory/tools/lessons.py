import argparse
import difflib
import fnmatch
import json
import os
import re
import sys
from datetime import date, datetime, timedelta
from pathlib import Path

AREAS = ["ui", "backend", "security", "data", "process", "style", "testing"]
SECRET = re.compile(r"(?i)(password|secret|token|api_?key)\s*[:=]\s*\S{6,}|-----BEGIN|AKIA[0-9A-Z]{16}|eyJ[A-Za-z0-9_\-]{10,}\.")


class LessonError(Exception):
    pass


def project_store(project):
    return Path(project).resolve() / ".ai" / "lessons.json"


def global_store():
    return Path(os.environ.get("DEVSTACK_LESSONS_GLOBAL", Path.home() / ".omp" / "agent" / "lessons.json"))


def load(path):
    if not path.exists():
        return {"version": 1, "lessons": []}
    return json.loads(path.read_text(encoding="utf-8"))


def save(path, data, prefix):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    render(path.with_name("LESSONS.md"), data, prefix)


def render(path, data, prefix):
    active = [l for l in data["lessons"] if l["status"] == "active"]
    lines = ["# Lessons", "", f"Generated by lessons.py on {date.today().isoformat()}. Do not edit by hand; use `lessons add`.", ""]
    for area in AREAS:
        items = sorted((l for l in active if l["area"] == area), key=lambda l: (-l["pinned"], -l["hits"], l["id"]))
        if not items:
            continue
        lines.append(f"## {area}")
        for l in items[:20]:
            lines.append("- " + line_for(l))
        lines.append("")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def line_for(lesson):
    tags = [lesson["id"], lesson["area"]]
    if lesson["hits"] > 1:
        tags.append(f"x{lesson['hits']}")
    if lesson.get("guard"):
        tags.append("guarded")
    text = f"[{' '.join(tags)}] {lesson['rule']}"
    if lesson.get("why"):
        text += f" Why: {lesson['why']}"
    if lesson.get("wrong"):
        text += f" Wrong: {lesson['wrong']}"
    if lesson.get("right"):
        text += f" Right: {lesson['right']}"
    return text


def next_id(data, prefix):
    numbers = [int(l["id"].split("-")[1]) for l in data["lessons"] if l["id"].startswith(prefix)]
    return f"{prefix}-{(max(numbers) if numbers else 0) + 1:04d}"


def similar(a, b):
    return difflib.SequenceMatcher(None, a.lower(), b.lower()).ratio()


def check_clean(*texts):
    for text in texts:
        if text and SECRET.search(text):
            raise LessonError("lesson berisi sesuatu yang mirip secret; tulis aturannya tanpa nilai asli")


def command_add(args):
    check_clean(args.rule, args.why, args.wrong, args.right)
    path, prefix = (global_store(), "G") if args.global_ else (project_store(args.project), "L")
    data = load(path)
    now = datetime.now().isoformat(timespec="seconds")
    for lesson in data["lessons"]:
        if lesson["status"] == "active" and lesson["area"] == args.area and similar(lesson["rule"], args.rule) >= 0.8:
            lesson["hits"] += 1
            lesson["updated"] = now
            for key in ("why", "wrong", "right"):
                if getattr(args, key) and not lesson.get(key):
                    lesson[key] = getattr(args, key)
            lesson["scope"] = sorted(set(lesson["scope"]) | set(args.scope or []))
            save(path, data, prefix)
            print(f"lessons: digabung ke {lesson['id']} (sekarang x{lesson['hits']})")
            hint(lesson)
            return
    lesson = {
        "id": next_id(data, prefix), "area": args.area, "rule": args.rule.strip(), "why": (args.why or "").strip(),
        "wrong": (args.wrong or "").strip(), "right": (args.right or "").strip(), "scope": args.scope or [],
        "source": args.source, "pinned": args.pin, "hits": 1, "created": now, "updated": now, "status": "active", "guard": None,
    }
    data["lessons"].append(lesson)
    save(path, data, prefix)
    print(f"lessons: disimpan {lesson['id']}")


def hint(lesson):
    if lesson["hits"] >= 2 and not lesson.get("guard"):
        print(f"lessons: {lesson['id']} terulang {lesson['hits']} kali. Jika bisa dicek dengan pola, buat guard: lessons.py guard {lesson['id']} --regex '...'")


def matches_scope(lesson, files):
    if not lesson["scope"]:
        return False
    return any(fnmatch.fnmatch(f, pattern) or fnmatch.fnmatch(Path(f).name, pattern) for f in files for pattern in lesson["scope"])


def command_recall(args):
    items = [(l, "project") for l in load(project_store(args.project))["lessons"]] + [(l, "global") for l in load(global_store())["lessons"]]
    files = args.files or []
    recent = datetime.now() - timedelta(days=30)
    scored = []
    for lesson, origin in items:
        if lesson["status"] != "active":
            continue
        score = min(lesson["hits"], 5) + (5 if lesson["pinned"] else 0)
        if args.area and lesson["area"] in args.area:
            score += 4
        if matches_scope(lesson, files):
            score += 4
        if datetime.fromisoformat(lesson["updated"]) > recent:
            score += 1
        if args.area and lesson["area"] not in args.area and not matches_scope(lesson, files) and not lesson["pinned"]:
            score -= 6
        scored.append((score, lesson))
    scored.sort(key=lambda s: (-s[0], s[1]["id"]))
    budget = args.budget * 4
    out, used = [], 0
    for score, lesson in scored:
        if score <= 0:
            continue
        text = "- " + line_for(lesson)
        if used + len(text) > budget:
            break
        out.append(text)
        used += len(text)
    if not out:
        print("lessons: belum ada pelajaran yang relevan")
        return
    print(f"Lessons to apply ({len(out)}):")
    print("\n".join(out))


def find(lesson_id, project):
    for path, prefix in ((project_store(project), "L"), (global_store(), "G")):
        data = load(path)
        for lesson in data["lessons"]:
            if lesson["id"] == lesson_id:
                return path, prefix, data, lesson
    raise LessonError(f"lesson {lesson_id} tidak ditemukan")


def command_hit(args):
    path, prefix, data, lesson = find(args.id, args.project)
    lesson["hits"] += 1
    lesson["updated"] = datetime.now().isoformat(timespec="seconds")
    save(path, data, prefix)
    print(f"lessons: {lesson['id']} sekarang x{lesson['hits']}")
    hint(lesson)


def command_guard(args):
    path, prefix, data, lesson = find(args.id, args.project)
    try:
        re.compile(args.regex)
    except re.error as error:
        raise LessonError(f"regex tidak valid: {error}")
    rules_dir = Path(args.project).resolve() / ".ai" / "rules"
    rules_dir.mkdir(parents=True, exist_ok=True)
    rules_file = rules_dir / "lessons.yml"
    existing = rules_file.read_text(encoding="utf-8") if rules_file.exists() else "rules:\n"
    rule_id = f"lesson-{lesson['id'].lower()}"
    if f"id: {rule_id}\n" in existing:
        raise LessonError(f"guard {rule_id} sudah ada di {rules_file}")
    include = args.include or lesson["scope"] or ["*"]
    message = (lesson["rule"] + (f" Right: {lesson['right']}" if lesson.get("right") else "")).replace('"', "'")
    block = [
        f"  - id: {rule_id}",
        f"    message: \"{message}\"",
        f"    severity: {args.severity}",
        f"    metadata: {{ area: {lesson['area']}, lesson: {lesson['id']} }}",
        "    languages: [generic]",
        "    paths:",
        "      include:",
        *[f"        - \"{pattern}\"" for pattern in include],
        "    pattern-regex: |-",
        f"      {args.regex}",
    ]
    rules_file.write_text(existing.rstrip("\n") + "\n" + "\n".join(block) + "\n", encoding="utf-8")
    lesson["guard"] = {"rule": rule_id, "regex": args.regex, "file": str(rules_file)}
    save(path, data, prefix)
    print(f"lessons: guard {rule_id} ditambahkan ke {rules_file}; audit.py akan menegakkannya")


def command_promote(args):
    gpath = global_store()
    gdata = load(gpath)
    pdata = load(project_store(args.project))
    candidates = [l for l in pdata["lessons"] if l["status"] == "active" and (l["id"] in (args.ids or []) or (not args.ids and l["hits"] >= 2 and not l["scope"]))]
    promoted = 0
    for lesson in candidates:
        if any(similar(g["rule"], lesson["rule"]) >= 0.8 and g["area"] == lesson["area"] for g in gdata["lessons"] if g["status"] == "active"):
            continue
        copy = dict(lesson, id=next_id(gdata, "G"), guard=None, origin=f"{Path(args.project).resolve().name}:{lesson['id']}")
        gdata["lessons"].append(copy)
        promoted += 1
    save(gpath, gdata, "G")
    print(f"lessons: {promoted} pelajaran dinaikkan ke global ({gpath})")


def command_compact(args):
    for path, prefix in ((project_store(args.project), "L"), (global_store(), "G")):
        data = load(path)
        if not data["lessons"]:
            continue
        merged = archived = 0
        active = [l for l in data["lessons"] if l["status"] == "active"]
        for i, a in enumerate(active):
            for b in active[i + 1:]:
                if b["status"] == "active" and a["status"] == "active" and a["area"] == b["area"] and similar(a["rule"], b["rule"]) >= 0.8:
                    a["hits"] += b["hits"]
                    a["scope"] = sorted(set(a["scope"]) | set(b["scope"]))
                    b["status"] = "merged"
                    b["merged_into"] = a["id"]
                    merged += 1
        cutoff = datetime.now() - timedelta(days=args.days)
        for lesson in data["lessons"]:
            if lesson["status"] == "active" and not lesson["pinned"] and not lesson.get("guard") and lesson["hits"] <= 1 and datetime.fromisoformat(lesson["updated"]) < cutoff:
                lesson["status"] = "archived"
                archived += 1
        save(path, data, prefix)
        print(f"lessons: {path}: {merged} digabung, {archived} diarsipkan")


def command_list(args):
    for path in (project_store(args.project), global_store()):
        data = load(path)
        active = [l for l in data["lessons"] if l["status"] == "active"]
        print(f"{path} ({len(active)} aktif)")
        for lesson in sorted(active, key=lambda l: (-l["hits"], l["id"])):
            print("  " + line_for(lesson))


def main():
    parser = argparse.ArgumentParser(description="Project and global lessons for devstack agents")
    parser.add_argument("--project", default=".")
    sub = parser.add_subparsers(dest="command", required=True)
    add = sub.add_parser("add", help="record a lesson from a correction or a failure")
    add.add_argument("--area", choices=AREAS, required=True)
    add.add_argument("--rule", required=True, help="one imperative sentence: what to do or never do")
    add.add_argument("--why")
    add.add_argument("--wrong", help="short example of the mistake")
    add.add_argument("--right", help="short example of the fix")
    add.add_argument("--scope", nargs="*", help="file globs where it applies, e.g. 'app/Http/Controllers/*.php'")
    add.add_argument("--source", choices=["operator", "gate", "review", "audit", "agent"], default="operator")
    add.add_argument("--pin", action="store_true", help="always recall this lesson")
    add.add_argument("--global", dest="global_", action="store_true", help="store for every project")
    recall = sub.add_parser("recall", help="print the lessons relevant to this task within a token budget")
    recall.add_argument("--area", nargs="*", choices=AREAS)
    recall.add_argument("--files", nargs="*")
    recall.add_argument("--budget", type=int, default=800, help="approximate tokens")
    hit = sub.add_parser("hit", help="the same mistake happened again")
    hit.add_argument("id")
    guard = sub.add_parser("guard", help="turn a lesson into an automatic check run by audit.py")
    guard.add_argument("id")
    guard.add_argument("--regex", required=True)
    guard.add_argument("--include", nargs="*")
    guard.add_argument("--severity", choices=["ERROR", "WARNING", "INFO"], default="ERROR")
    promote = sub.add_parser("promote", help="copy lessons that apply everywhere to the global store")
    promote.add_argument("ids", nargs="*")
    compact = sub.add_parser("compact", help="merge duplicates and archive stale lessons")
    compact.add_argument("--days", type=int, default=120)
    sub.add_parser("list")
    args = parser.parse_args()
    handlers = {"add": command_add, "recall": command_recall, "hit": command_hit, "guard": command_guard, "promote": command_promote, "compact": command_compact, "list": command_list}
    try:
        handlers[args.command](args)
    except (LessonError, json.JSONDecodeError) as error:
        print(f"lessons: FAIL {error}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
